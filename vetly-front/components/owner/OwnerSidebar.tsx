interface OwnerSidebarProps {
  isOpen: boolean;
  onClose: () => void;
}

export default function OwnerSidebar({ isOpen, onClose }: OwnerSidebarProps) {
  const pathname = usePathname();
  const router = useRouter();
  const { logout } = useAuth();
  const { total: activeMedsCount, refetch: refetchMeds } = useMyMedications(true);
  const { notifications, refetch: refetchNotifs } = useMyNotifications();

  const unreadNotifCount = notifications.filter(n => !n.is_read).length;

  useEffect(() => {
    const handler = () => refetchNotifs();
    window.addEventListener('vetly:notifications-updated', handler);
    return () => window.removeEventListener('vetly:notifications-updated', handler);
  }, [refetchNotifs]);

  useEffect(() => {
    const handler = () => refetchMeds();
    window.addEventListener('vetly:medications-updated', handler);
    return () => window.removeEventListener('vetly:medications-updated', handler);
  }, [refetchMeds]);

  useEffect(() => {
    const interval = setInterval(() => {
      refetchNotifs();
      refetchMeds();
    }, 30000);
    return () => clearInterval(interval);
  }, [refetchNotifs, refetchMeds]);

  const handleLogout = () => {
    logout();
    router.push('/owner/login');
  };

  const handleNavClick = () => {
    onClose();
  };

  const sidebarContent = (
    <aside className="h-full w-64 bg-white border-r border-slate-100 flex flex-col">
      {/* Logo */}
      <div className="p-6 border-b border-slate-100">
        <Link href="/owner/dashboard" className="flex items-center gap-3" onClick={handleNavClick}>
          <div className="w-10 h-10 bg-teal-600 rounded-xl flex items-center justify-center">
            <svg className="w-6 h-6 text-white" fill="none" viewBox="0 0 24 24" stroke="currentColor">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M4.318 6.318a4.5 4.5 0 000 6.364L12 20.364l7.682-7.682a4.5 4.5 0 00-6.364-6.364L12 7.636l-1.318-1.318a4.5 4.5 0 00-6.364 0z" />
            </svg>
          </div>
          <div>
            <span className="text-xl font-bold text-slate-900">Vetly</span>
          </div>
        </Link>
      </div>

      {/* Navigation */}
      <nav className="flex-1 p-4 space-y-1 overflow-y-auto">
        {navItems.map((item) => {
          const isActive = pathname === item.href;
          return (
            <Link
              key={item.href}
              href={item.href}
              onClick={handleNavClick}
              className={`flex items-center gap-3 px-4 py-3 rounded-xl text-sm font-medium transition-all ${
                isActive
                  ? 'bg-teal-50 text-teal-700'
                  : 'text-slate-600 hover:bg-slate-50 hover:text-slate-900'
              }`}
            >
              <span className={isActive ? 'text-teal-600' : 'text-slate-400'}>
                {item.icon}
              </span>
              {item.name}
              {item.badgeKey === 'medications' && activeMedsCount > 0 && (
                <span className="ml-auto bg-teal-100 text-teal-700 text-xs font-bold px-2 py-0.5 rounded-full">
                  {activeMedsCount}
                </span>
              )}
              {item.badgeKey === 'notifications' && unreadNotifCount > 0 && (
                <span className="ml-auto bg-amber-100 text-amber-700 text-xs font-bold px-2 py-0.5 rounded-full">
                  {unreadNotifCount}
                </span>
              )}
            </Link>
          );
        })}
      </nav>

      {/* Bottom Navigation */}
      <div className="p-4 border-t border-slate-100">
        {bottomNavItems.map((item) => {
          const isActive = pathname === item.href;
          return (
            <Link
              key={item.href}
              href={item.href}
              onClick={handleNavClick}
              className={`flex items-center gap-3 px-4 py-3 rounded-xl text-sm font-medium transition-all ${
                isActive
                  ? 'bg-teal-50 text-teal-700'
                  : 'text-slate-600 hover:bg-slate-50 hover:text-slate-900'
              }`}
            >
              <span className={isActive ? 'text-teal-600' : 'text-slate-400'}>
                {item.icon}
              </span>
              {item.name}
            </Link>
          );
        })}

        {/* Logout */}
        <button
          onClick={handleLogout}
          className="flex items-center gap-3 px-4 py-3 rounded-xl text-sm font-medium text-red-600 hover:bg-red-50 transition-all mt-2 w-full"
        >
          <svg className="w-5 h-5" fill="none" viewBox="0 0 24 24" stroke="currentColor">
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M17 16l4-4m0 0l-4-4m4 4H7m6 4v1a3 3 0 01-3 3H6a3 3 0 01-3-3V7a3 3 0 013-3h4a3 3 0 013 3v1" />
          </svg>
          Αποσύνδεση
        </button>
      </div>
    </aside>
  );

  return (
    <>
      {/* Desktop sidebar */}
      <div className="hidden md:block fixed left-0 top-0 h-screen w-64 z-40">
        {sidebarContent}
      </div>

      {/* Mobile overlay */}
      {isOpen && (
        <div className="md:hidden fixed inset-0 z-50 flex">
          {/* Backdrop */}
          <div
            className="fixed inset-0 bg-black/40"
            onClick={onClose}
            aria-hidden="true"
          />
          {/* Sidebar panel */}
          <div className="relative w-64 h-full flex-shrink-0 z-10">
            {sidebarContent}
          </div>
        </div>
      )}
    </>
  );
}
